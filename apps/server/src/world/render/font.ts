/** 在 (x, y) 处写一行大写文字，scale 为像素放大倍数；返回文字宽度 */
export function drawText(r: Raster, x: number, y: number, text: string, color: Rgb, scale = 1, alpha = 1): number {
  let cx = x;
  for (const ch of text.toUpperCase()) {
    const glyph = G[ch] ?? G[' '];
    for (let row = 0; row < 7; row++) {
      for (let col = 0; col < 5; col++) {
        if (glyph[row][col] !== '1') continue;
        r.rect(cx + col * scale, y + row * scale, scale, scale, color, alpha);
      }
    }
    cx += 6 * scale;
  }
  return cx - x;
}

export function textWidth(text: string, scale = 1): number {
  return text.length * 6 * scale;
}
